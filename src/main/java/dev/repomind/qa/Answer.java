package dev.repomind.qa;

import java.util.List;

/**
 * @param citations the sources the answer actually cites, in order of first mention
 * @param sources every source that was shown to the model
 * @param model the model that answered, when the provider reports it
 * @param cache whether this answer was generated now or reused from an earlier question
 */
public record Answer(String answer, List<Source> citations, List<Source> sources, String model, long latencyMs,
		Cache cache) {

	/** @param index the number the model uses to cite this source, e.g. {@code [2]} */
	public record Source(int index, String location, String symbol) {
	}

	/**
	 * @param matchedQuestion for a semantic hit, the earlier question whose answer is reused, so a
	 * client can show "answer to a similar question" rather than pass it off as fresh
	 * @param similarity cosine similarity to that question
	 */
	public record Cache(Status status, String matchedQuestion, Double similarity) {

		public static final Cache MISS = new Cache(Status.MISS, null, null);

		public enum Status {
			/** Generated by the model for this request. */
			MISS,
			/** Same question as an earlier one, up to case, spacing and trailing punctuation. */
			EXACT,
			/** A differently worded question whose embedding is nearly identical. */
			SEMANTIC
		}

	}

	Answer withCache(Cache cache, long latencyMs) {
		return new Answer(answer, citations, sources, model, latencyMs, cache);
	}

}
